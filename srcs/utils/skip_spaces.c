#include "minishell.h"

int	skip_spaces(char *line, int *i)
{
	int	j;

	j = 0;
	if (!i)
		i = &j;
	if (!line || !line[*i])
		return (0);
	while (line[*i] == ' ')
		(*i)++;
	if (!line[*i])
		return (0);
	return (1);
}
